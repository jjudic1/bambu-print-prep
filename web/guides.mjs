/**
 * JSON-LD, two blocks per page. The FAQ is the one that earns its place -- it
 * is the shape an answer engine reads a question-and-answer off. The breadcrumb
 * is there so the page is understood as sitting under the app rather than
 * floating on its own.
 */
function jsonLd(page) {
  const faq = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: page.faq.map(([q, a]) => ({
      '@type': 'Question',
      name: q,
      acceptedAnswer: { '@type': 'Answer', text: a },
    })),
  }
  const crumbs = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: BRAND, item: SITE + '/' },
      {
        '@type': 'ListItem',
        position: 2,
        name: page.h1,
        item: SITE + '/' + page.slug,
      },
    ],
  }
  return [faq, crumbs]
    .map((o) => '<script type="application/ld+json">\n'
      + JSON.stringify(o, null, 2) + '\n</script>')
    .join('\n')
}

function faqBlock(page) {
  const items = page.faq
    .map(([q, a]) => '<h3>' + escape(q) + '</h3>\n<p>' + dashes(a) + '</p>')
    .join('\n')
  return '<h2>Common questions</h2>\n' + items
}

function footerLinks(page) {
  const others = PAGES.filter((p) => p.slug !== page.slug)
    .map((p) => '<li><a href="/' + p.slug + '">' + escape(LABEL[p.slug])
      + '</a></li>')
    .join('\n')
  return '<footer>\n<p><b>' + BRAND + '</b> is a free page that prepares 3D '
    + 'models for Bambu Lab printers on an iPad. Nothing is installed, and your '
    + 'model is not uploaded.</p>\n<ul>\n' + others + '\n</ul>\n</footer>'
}

