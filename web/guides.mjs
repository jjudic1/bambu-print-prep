/**
 * robots.txt. The default is allow, so naming the answer engines changes
 * nothing technically -- it is here because "are we blocking GPTBot" is a
 * question that gets asked, and a file that answers it in writing settles it.
 * The dashboard is behind a key and already carries its own noindex; it is
 * named here as well so it is never fetched in the first place.
 */
export function renderRobots() {
  const agents = [
    'GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-User',
    'anthropic-ai', 'PerplexityBot', 'Perplexity-User', 'Google-Extended',
    'Applebot-Extended', 'CCBot', 'Bingbot', 'meta-externalagent',
  ]
  return '# ' + BRAND + ' -- everything here is meant to be found.\n'
    + '# The answer engines are named explicitly so that "is this site\n'
    + '# blocking them" has a written answer rather than an assumed one.\n\n'
    + 'User-agent: *\n'
    + 'Allow: /\n'
    + 'Disallow: /dashboard\n'
    + 'Disallow: /dashboard.html\n\n'
    + agents.map((a) => 'User-agent: ' + a + '\nAllow: /\n').join('\n')
    + '\nSitemap: ' + SITE + '/sitemap.xml\n'
}

/** sitemap.xml. The app first, then the pages -- all of them real files. */
export function renderSitemap(today) {
  const urls = [{ loc: SITE + '/', priority: '1.0' }].concat(
    PAGES.map((p) => ({ loc: SITE + '/' + p.slug, priority: '0.8' })))
  const body = urls
    .map(({ loc, priority }) => '  <url>\n'
      + '    <loc>' + loc + '</loc>\n'
      + '    <lastmod>' + today + '</lastmod>\n'
      + '    <changefreq>monthly</changefreq>\n'
      + '    <priority>' + priority + '</priority>\n'
      + '  </url>')
    .join('\n')
  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    + body + '\n</urlset>\n'
}
