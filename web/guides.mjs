/**
 * The pages a search engine can actually read.
 *
 * The app is a React page with an empty <div id="root"> in the HTML. Google
 * will render it eventually; the crawlers behind AI answers -- GPTBot,
 * ClaudeBot, PerplexityBot, OAI-SearchBot -- fetch the HTML and stop. To all of
 * them the product was a blank page titled "Handoff3D", which is a word nobody
 * types into a search box. These are static files with the answer written out
 * in the HTML, one page per question people actually ask.
 *
 * They are plain files in web/public/, not Vite entry points, deliberately:
 * nothing here needs bundling, and a page that must survive with JavaScript
 * switched off should not go through a JavaScript build to get there. Vercel
 * copies public/ to the site root, and `cleanUrls` in vercel.json serves them
 * without the .html. The filesystem is checked before the catch-all rewrite, so
 * they win over it without needing a rewrite of their own.
 *
 * ONE DELIBERATE BREAK WITH THE COPY RULES. Section 6 of the spec bans mesh,
 * manifold, normals, infill, gcode and slice from user-facing strings, and
 * every string in the app obeys it. These pages cannot: "slice" and "STL" are
 * the words people type, and a page that avoids them cannot be found by anyone
 * searching for them. So the jargon appears where it is the question, and the
 * answer under it is in plain words. Nothing in web/src/ is affected.
 *
 * Sources stay ASCII and typography goes in as entities, same as handoff.js.
 * Generated by build-guides.mjs; the output is committed, and
 * tests/test_guides.py fails if the two have drifted.
 */

